/**
 * 操作结果契约：诚实三态（docs/123 §一.5）。
 *
 * 【为什么要有它】一次操作的「成没成功 / 降没降级 / 为什么没做」必须**在类型层可判别**，
 * 否则消费方只能靠脑补，复杂度就漏进散落的 catch 里（7 步法 Step 4 第 1 问）。
 *
 * 【O4 · 定位红线 —— 只用于跨系统边界】（docs/123 §一.5 O4 / §二.7 P7）
 * 本类型**只**给「跨系统边界」的操作用：**入轨 / 导出 / 落盘**——它们会碰到
 * 环境（编码器 / 磁盘 / 素材可读性），失败是**系统错**（不可判定）。
 * **纯函数一律返回纯值**（新数组 / `null` / 原样返回），
 * 因为纯函数的「失败」是**输入不合法**（可判定，调用方在调用前就能排除），
 * 给它们套 `OpResult` = 宽接口 + 薄实现 = 泄漏。
 *
 * 【O1 · 何时才是 reject】`reject` **只准用于语义冲突**（类型不符，如把音频拖进视频轨的判据）；
 * **位置冲突一律 `ok` + 自动落最近合法位**（docs/120 C14.3）——
 * 「这里放不下」不该是一个失败，它只是需要挪一下。
 *
 * 【O3 · 无静默 null】纯函数返回 `null` 时（如 `splitAt` 落在边界），
 * 调用处必须转成「**置灰 + tooltip**」的不可用状态，不得静默忽略。
 */
export type OpResult<T> =
  | { status: 'ok'; value: T }
  | { status: 'degraded'; value: T; reason: string }
  | { status: 'reject'; reason: string; expected?: string };

