/**
 * 图片尺寸上下限（**唯一真源** · TD-03-24）。
 *
 * 【为什么要有它】此前 `4096` 在 image 域散成 7 处字面量、`64` 同样散落 ——
 * `OverlayEditor`（画布宽/高输入）4 处 · `GridMergeNode`（输出尺寸）2 处 · `PanoramaNode`（球体贴图请求）1 处。
 * 改上限要逐处找，**漏一处即出现「一个输入框能输 8192、另一个不能」的不一致**。
 *
 * 【为什么三处共用同一上限】用途不同（① 用户可输入的画布/输出尺寸；② 请求服务端出图的单边边长），
 * 但受**同一工程约束**：单张图单边超过 4096 时浏览器解码/内存不可接受 ⇒ 同一判据，值必须一致。
 * 若将来某处确需突破该值，应**在此处显式分列并写明理由**，而不是某处偷偷写死另一个数字。
 */
/** 图片单边最小像素（输入下限） */
export const IMG_MIN_DIM = 64;
/** 图片单边最大像素（输入上限 ／ 出图请求边长上限） */
export const IMG_MAX_DIM = 4096;
