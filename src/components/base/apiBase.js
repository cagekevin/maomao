/**
 * 【重要】localTool 后端 API 地址统一入口。
 *
 * 为什么硬编码 http://127.0.0.1:18080 而不是配置化 / 相对路径：
 *  - 当前是【原型阶段】：前端 dev server 跑在 5180，localTool 后端跑在 18080。
 *    两者跨端口，前端页面无法用相对路径访问后端，必须用绝对地址。
 *  - 【正式发布】：前端页面会直接部署到 localTool 的 18080 端口
 *    （即原型里的 5180 页面，正式时变成 18080 打开，与 localTool 同源）。
 *    届时该地址仍指向本机 18080，无需改动即可正常工作。
 *  - 因此这里写死 127.0.0.1:18080 是刻意为之，不是随意写死，也不是漏了配置化。
 *    若要支持局域网 / 远程 localTool，再改为可配置项即可。
 *
 * 所有 API 层文件（imageApi/videoApi/filesApi/kvStore/...）统一从这里 import API_BASE，
 * 不要各自重复硬编码地址。
 */
export const API_BASE = 'http://127.0.0.1:18080'
